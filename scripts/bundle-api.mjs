import * as esbuild from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

await esbuild.build({
  absWorkingDir: root,
  entryPoints: {
    portfolio: 'server/vercel-portfolio.ts',
    chat: 'server/vercel-chat.ts',
  },
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  outdir: 'api',
  logLevel: 'info',
  legalComments: 'none',
  minify: false,
  packages: 'external',
  banner: {
    js: '/* generated by scripts/bundle-api.mjs — do not edit */',
  },
});
