import * as esbuild from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

await esbuild.build({
  absWorkingDir: root,
  entryPoints: ['server/vercel-portfolio.ts'],
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  outfile: 'api/portfolio.js',
  logLevel: 'info',
  legalComments: 'none',
  minify: false,
  banner: {
    js: '/* generated by scripts/bundle-api.mjs from server/vercel-portfolio.ts — do not edit */',
  },
});
